import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { parse as parseYaml, stringify as stringifyYaml } from 'yaml'
import { dshHome, resolveDsh } from './bins.ts'
import { describeTimeout, idleTimeoutMs, runProcess, turnTimeoutMs, type ProcessResult } from './process.ts'
import { runtimeDir } from '../paths.ts'
import type { HarnessAdapter, RunInput, RunOutput } from './types.ts'
import type { Character, ToolTrace } from '../types.ts'

const DSH_MODELS = ['deepseek-flash', 'deepseek-v4-pro']

const CREDENTIAL_HINT = [
  '修复建议（任选其一）：',
  '1. 打开 DSH Web（http://127.0.0.1:3080）的 Models 页，重新保存一次 DeepSeek API key；',
  '2. 在启动 agent-crowd 的终端里 `$env:DEEPSEEK_API_KEY="sk-..."` 后重启；',
  '3. 确认 `~/.dsh/.credentials.yaml` 里的 `refs.DEEPSEEK_API_KEY` 可读。',
].join('\n')

interface DshRuntime {
  patchPath: string
  provider: string
  model: string
}

/**
 * DSH 0.2 replaced the file-backed settings plugin with an abstract settings
 * seam, so pointing `settings` at a copied settings.yaml only works on older
 * builds. Detect what the installed build actually composes instead of assuming.
 */
let fileSettingsCache: boolean | undefined
function usesFileSettingsPlugin(): boolean {
  if (fileSettingsCache !== undefined) return fileSettingsCache
  fileSettingsCache = false
  const spec = resolveDsh()
  const binPath = spec?.argsPrefix[0]
  if (!binPath) return fileSettingsCache
  const basePatch = join(dirname(dirname(binPath)), 'node_modules', '@deepseek-ai', 'dsh-base', 'cordis.patch.yml')
  if (!existsSync(basePatch)) return fileSettingsCache
  try {
    const text = readFileSync(basePatch, 'utf8')
    const match = text.match(/- id: settings\s*\n\s+name:\s*'([^']+)'/)
    fileSettingsCache = match?.[1] === '@deepseek-ai/dsh-settings-file'
  } catch {
    fileSettingsCache = false
  }
  return fileSettingsCache
}

/**
 * dsh resolves its API key from the process environment or its credentials
 * service. When agent-crowd itself is started from a shell without
 * DEEPSEEK_API_KEY, fall back to the key already stored in dsh's own
 * ~/.dsh/.credentials.yaml so switching terminals can't silently break dsh
 * characters. The managed store still wins inside dsh; this is only the
 * inherited-environment fallback it documents.
 */
function storedDeepseekKey(): string | undefined {
  try {
    const credentialsPath = join(dshHome(), '.credentials.yaml')
    if (!existsSync(credentialsPath)) return undefined
    const doc = parseYaml(readFileSync(credentialsPath, 'utf8')) as { refs?: Record<string, unknown> } | null
    const value = doc?.refs?.DEEPSEEK_API_KEY
    if (typeof value !== 'string') return undefined
    const key = value.trim()
    if (!key || key.startsWith('${') || key.startsWith('env:')) return undefined
    return key
  } catch {
    return undefined
  }
}

function apiKeyForChild(): string | undefined {
  return process.env.DEEPSEEK_API_KEY?.trim() || storedDeepseekKey()
}

/** Where the DeepSeek key will come from for the next dsh turn. */
export function dshCredentialStatus(): 'env' | 'store' | 'missing' {
  if (process.env.DEEPSEEK_API_KEY?.trim()) return 'env'
  return storedDeepseekKey() ? 'store' : 'missing'
}

/**
 * The headless profile reads its model from the `agent-default-model` entry;
 * a per-character `--patch` overlay sets provider/model for one turn.
 */
function writeRuntime(character: Character): DshRuntime {
  const dir = runtimeDir('dsh', character.id)
  const settingsPath = join(dshHome(), 'settings.yaml')
  const includeSettings = usesFileSettingsPlugin() && existsSync(settingsPath)

  let previous: Record<string, unknown> = {}
  let doc: Record<string, unknown> = {}
  if (includeSettings) {
    try {
      const parsed = parseYaml(readFileSync(settingsPath, 'utf8'))
      if (parsed && typeof parsed === 'object') doc = parsed as Record<string, unknown>
      previous = (doc['agent-default-model'] ?? {}) as Record<string, unknown>
    } catch {
      doc = {}
    }
  }

  const requested = character.model.trim()
  let provider = String(previous.provider ?? 'deepseek-official')
  let model = String(previous.model ?? 'deepseek-flash')
  if (requested) {
    const slash = requested.indexOf('/')
    if (slash > 0) {
      provider = requested.slice(0, slash)
      model = requested.slice(slash + 1)
    } else {
      model = requested
    }
  }

  const patchLines = ['# generated by agent-crowd for one character turn']

  if (includeSettings) {
    doc['agent-default-model'] = { ...previous, provider, model }
    const copyPath = join(dir, 'settings.yaml')
    writeFileSync(copyPath, stringifyYaml(doc), 'utf8')
    patchLines.push(
      '- id: settings',
      '  config:',
      `    path: ${JSON.stringify(copyPath.replace(/\\/g, '/'))}`,
    )
  }

  patchLines.push(
    '- id: agent-default-model',
    '  config:',
    `    provider: ${JSON.stringify(provider)}`,
    `    model: ${JSON.stringify(model)}`,
    '',
  )

  const patchPath = join(dir, 'patch.yml')
  writeFileSync(patchPath, patchLines.join('\n'), 'utf8')
  return { patchPath, provider, model }
}

interface Attempt {
  result: ProcessResult
  text: string
  thinking: string
  toolTraces: ToolTrace[]
}

async function attemptRun(
  spec: NonNullable<ReturnType<typeof resolveDsh>>,
  runtime: DshRuntime,
  input: RunInput,
  apiKey: string | undefined,
): Promise<Attempt> {
  let stdoutText = ''
  let thinking = ''
  const toolTraces: ToolTrace[] = []

  const result = await runProcess(
    spec.command,
    [...spec.argsPrefix, '--profile', 'headless', '--patch', runtime.patchPath, input.prompt],
    {
      cwd: input.cwd,
      signal: input.signal,
      timeoutMs: turnTimeoutMs(),
      idleTimeoutMs: idleTimeoutMs(),
      onSpawn: input.onSpawn,
      ...(apiKey ? { env: { DEEPSEEK_API_KEY: apiKey } } : {}),
      onStdoutLine: (line) => {
        stdoutText += line + '\n'
        input.emit({ kind: 'text', text: line + '\n' })
      },
      onStderrLine: (line) => {
        const trimmed = line.trim()
        if (!trimmed) return
        if (trimmed.length > 500) return
        if (/^(info|debug|warn|error)\b/i.test(trimmed)) return
        thinking += trimmed + '\n'
        if (thinking.length > 8000) thinking = thinking.slice(-8000)
        input.emit({ kind: 'thinking', text: trimmed })
      },
    },
  )

  return { result, text: stdoutText.trim(), thinking: thinking.trim(), toolTraces }
}

/**
 * DeepSeek Harness adapter: `dsh --profile headless --patch <turn patch> "<task>"`.
 * The final assistant message lands on stdout; reasoning/log lines land on stderr.
 */
export const dshAdapter: HarnessAdapter = {
  id: 'dsh',
  label: 'DeepSeek Harness',

  async run(input: RunInput): Promise<RunOutput> {
    const spec = resolveDsh()
    if (!spec) {
      throw new Error(
        '找不到 DeepSeek Harness。请确认 `dsh` 已全局安装，或用环境变量 AC_DSH_BIN 指定 dsh/lib/bin.js 的完整路径。',
      )
    }

    const started = Date.now()
    const runtime = writeRuntime(input.character)

    let attempt = await attemptRun(spec, runtime, input, apiKeyForChild())

    // A credentials read can lose a race with another dsh process (upgrades,
    // the web Models page). One fresh attempt with a re-read key is enough.
    const missingCredential = (value: Attempt) =>
      !value.text && !input.signal.aborted && /MISSING_CREDENTIAL/.test(value.result.stderr)
    if (missingCredential(attempt)) {
      await new Promise((resolve) => setTimeout(resolve, 1200))
      const retryKey = apiKeyForChild()
      if (retryKey) attempt = await attemptRun(spec, runtime, input, retryKey)
    }

    const { result, text, thinking, toolTraces } = attempt
    const stderrTail = result.stderr.trim().slice(-4000)
    let error =
      result.spawnError ||
      (result.aborted
        ? '已停止'
        : describeTimeout(result) ||
          (result.code !== 0 && !text
            ? stderrTail || `dsh 退出码 ${result.code}`
            : undefined))

    if (error && /MISSING_CREDENTIAL/.test(error)) {
      error = `${error}\n\n${CREDENTIAL_HINT}`
    }

    return {
      text,
      thinking: thinking || undefined,
      toolTraces,
      pid: result.pid,
      exitCode: result.code ?? -1,
      durationMs: Date.now() - started,
      error: error || undefined,
    }
  },

  async listModels(): Promise<string[]> {
    return [...DSH_MODELS]
  },
}
